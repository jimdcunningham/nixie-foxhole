import assert from 'node:assert/strict';
import { mkdir, writeFile, unlink } from 'node:fs/promises';
import path from 'node:path';
import { whitePng, triangleGlb } from '../tests/preview-fixtures.mjs';

export async function checkComparisons(app, page, base) {
  const root = path.join(base,'comparisons'); await mkdir(root);
  const put = (file,body) => writeFile(path.join(root,file),body);
  const largeBody = 'x'.repeat(1_100_000);
  await put('large-manifest.json',JSON.stringify({payload:largeBody,setting:1}));
  await put('icon.png',whitePng());
  await put('model.glb',triangleGlb());
  await put('deleted.glb',triangleGlb());
  await put('manifest.json',JSON.stringify({version:1,assets:{hospital:{health:100},removed:{value:1}}}));
  await app.evaluate(({BrowserWindow,dialog},root) => {
    BrowserWindow.getAllWindows()[0].setSize(1240,820);
    dialog.showOpenDialog = async () => ({canceled:false,filePaths:[root]});
  },root);
  await page.getByRole('button',{name:'Open Assets Directory',exact:true}).click();
  await page.getByRole('treeitem',{name:'manifest.json',exact:true}).waitFor();
  await app.evaluate(({Menu}) => Menu.getApplicationMenu().items.find(item => item.label === '&Review').submenu.items.find(item => item.label === 'Approve Current Assets as Baseline').click());
  await page.getByText('0 Changes',{exact:true}).waitFor();
  await put('large-manifest.json',JSON.stringify({payload:largeBody,setting:2}));
  await put('icon.png',whitePng([255,255,255,128],32,16));
  await put('model.glb',triangleGlb({nodes:[{mesh:0,scale:[1.4,1.4,1.4]}],materials:[{doubleSided:true,pbrMetallicRoughness:{baseColorFactor:[.2,.5,.95,1],metallicFactor:0,roughnessFactor:1}}]}));
  await put('manifest.json',JSON.stringify({version:1,assets:{hospital:{health:150},added:{value:2}}}));
  await put('added.png',whitePng([255,90,80,255]));
  await unlink(path.join(root,'deleted.glb'));
  await page.getByRole('button',{name:'Refresh Assets',exact:true}).click();
  await page.getByText('6 Changes',{exact:true}).waitFor();
  async function select(name) {
    await page.locator('[id='+JSON.stringify('entry-'+encodeURIComponent(name))+']').click();
    await page.waitForFunction(name => document.querySelector('.asset-preview')?.getAttribute('data-preview-path') === name && document.querySelector('.asset-preview')?.getAttribute('aria-busy') === 'false',name);
  }
  await select('icon.png');
  await page.getByRole('button',{name:'Compare',exact:true}).click();
  await page.locator('.preview-layer:not(.is-pending) .image-comparison').waitFor();
  assert.equal(await page.locator('.preview-layer:not(.is-pending) .image-comparison img').count(),2);
  await page.getByRole('button',{name:'Swipe',exact:true}).click();
  await page.getByRole('slider',{name:'Swipe Position'}).evaluate(element => { element.value = '30'; element.dispatchEvent(new Event('input',{bubbles:true})); });
  assert.match(await page.locator('.swipe-divider').getAttribute('style'),/30%/);
  await page.getByRole('button',{name:'Overlay',exact:true}).click();
  await page.getByRole('slider',{name:'Working Opacity'}).evaluate(element => { element.value = '40'; element.dispatchEvent(new Event('input',{bubbles:true})); });
  await page.getByRole('button',{name:'Difference',exact:true}).click();
  await page.getByText(/512 \/ 512 pixels differ/).waitFor();
  assert.equal(await page.locator('.image-comparison canvas').getAttribute('width'),'32');
  await select('manifest.json');
  await page.locator('.manifest-table').waitFor();
  assert.match(await page.locator('.manifest-table').innerText(),/\/assets\/hospital\/health/);
  assert.equal(await page.locator('.manifest-table tbody tr').count(),3);
  await page.getByRole('searchbox',{name:'Search Manifest Changes'}).fill('health');
  assert.equal(await page.locator('.manifest-table tbody tr').count(),1);
  await select('large-manifest.json');
  await page.locator('.manifest-table').waitFor();
  assert.match(await page.locator('.manifest-table').innerText(),/\/setting/);
  assert.equal(await page.locator('.manifest-table tbody tr').count(),1);
  await page.getByRole('button',{name:'Source',exact:true}).click();
  assert.equal(await page.getByText('Source display limited to the first 1 MB.',{exact:true}).count(),2);
  await select('model.glb');
  await page.locator('[data-side=approved] .model-viewport canvas').waitFor();
  await page.locator('[data-side=working] .model-viewport canvas').waitFor();
  assert.equal(await page.locator('.model-comparison .model-message').count(),0);
  const a = page.locator('[data-side=approved] .model-viewport canvas');
  const b = page.locator('[data-side=working] .model-viewport canvas');
  const before = await b.screenshot(); const box = await a.boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2); await page.mouse.down();
  await page.mouse.move(box.x+box.width/2+70,box.y+box.height/2+30,{steps:8}); await page.mouse.up();
  assert.notDeepEqual(await b.screenshot(),before);
  await page.getByRole('button',{name:'A · Approved',exact:true}).click();
  await page.getByRole('button',{name:'Reset Views',exact:true}).click();
  await page.getByRole('button',{name:'B · Working',exact:true}).click();
  await page.getByRole('button',{name:'Side by Side',exact:true}).click();
  await select('deleted.glb');
  await page.locator('.model-comparison').getByText('Deleted from working files',{exact:true}).waitFor();
  await select('added.png');
  await page.locator('.image-comparison').getByText('Not in the approved baseline',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Preview',exact:true}).click();
  await page.locator('.preview-layer:not(.is-pending) .image-preview').waitFor();
  const escaped = await page.evaluate(async () => { const root = await window.foxwatch.getRoot(); try { await window.foxwatch.comparison(root.id,'../outside.png'); return false; } catch { return true; } });
  assert.equal(escaped,true);
}
