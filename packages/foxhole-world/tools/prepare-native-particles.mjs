import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';

const xyz=v=>[v?.X||0,v?.Y||0,v?.Z||0];
// Native raw distributions store constant/uniform bounds independently of their
// optional distribution UObject. Preserve those bounds, including reversed ones.
function scalar(d,fallback=0){
 if(!d)return [fallback,fallback];
 if(d.MinValue!==undefined||d.MaxValue!==undefined)return [d.MinValue??0,d.MaxValue??0];
 const t=d.Table;if(t?.Values?.length)return [t.Values[0],t.Op===2?t.Values[1]:t.Values[0]];
 return [fallback,fallback];
}
function vector(d){
 if(d?.MinValueVec||d?.MaxValueVec)return [xyz(d.MinValueVec),xyz(d.MaxValueVec)];
 const t=d?.Table,v=t?.Values;if(v?.length>=3)return [v.slice(0,3),t.Op===2?v.slice(3,6):v.slice(0,3)];
 return [[0,0,0],[0,0,0]];
}
export function compileNativeParticleModules(exports){
 const resolve=ref=>{
  const name=ref?.ObjectName?.match(/[.:]([^:.']+)'$/)?.[1];if(!name)return undefined;
  const index=ref.ObjectPath?.match(/\.(\d+)$/)?.[1],object=index===undefined?undefined:exports[Number(index)];
  if(object?.Name===name)return object;
  const matches=exports.filter(o=>o.Name===name);if(matches.length>1)throw Error('Ambiguous native particle reference '+ref.ObjectName);
  return matches[0];
 };
 const system=exports.find(o=>o.Type==='ParticleSystem'),emitters={};
 for(const ref of system?.Properties?.Emitters||[]){
  const emitter=resolve(ref);if(!emitter)continue;
  const level=resolve(emitter.Properties?.LODLevels?.[0]),p=level?.Properties||{};
  const required=resolve(p.RequiredModule)?.Properties||{},spawn=resolve(p.SpawnModule)?.Properties||{};
  const modules=(p.Modules||[]).map(resolve).filter(o=>o&&o.Properties?.bEnabled!==false);
  const find=type=>modules.find(o=>o.Type===type)?.Properties;
  const volume=modules.filter(o=>/^ParticleModuleLocationPrimitive(Sphere|Cylinder)(_Seeded)?$/.test(o.Type)).map(o=>{
   const v=o.Properties||{};return {shape:o.Type.includes('Sphere')?'sphere':'cylinder',radius:scalar(v.StartRadius),height:scalar(v.StartHeight),axis:({PMLPC_HEIGHTAXIS_X:0,PMLPC_HEIGHTAXIS_Y:1,PMLPC_HEIGHTAXIS_Z:2})[v.HeightAxis]??2,
    positive:['X','Y','Z'].map(a=>v['Positive_'+a]!==false),negative:['X','Y','Z'].map(a=>v['Negative_'+a]!==false),surface:v.SurfaceOnly===true,location:vector(v.StartLocation),velocity:v.Velocity===true,velocityScale:scalar(v.VelocityScale),radialVelocity:v.RadialVelocity!==false};
  });
  const orbit=find('ParticleModuleOrbit');
  emitters[emitter.Name]={enabled:p.bEnabled!==false,loops:required.EmitterLoops??0,duration:required.EmitterDuration??1,delay:required.EmitterDelay??0,bursts:(spawn.BurstList||[]).map(b=>({count:b.Count??0,countLow:b.CountLow??-1,time:b.Time??0})),volumes:volume,
   drag:scalar(find('ParticleModuleAccelerationDrag')?.DragCoefficientRaw),rotation:scalar(find('ParticleModuleRotation')?.StartRotation),rotationRate:scalar(find('ParticleModuleRotationRate')?.StartRotationRate),
   ...(orbit?{orbit:{offset:vector(orbit.OffsetAmount),rotation:vector(orbit.RotationAmount),rate:vector(orbit.RotationRateAmount)}}:{}),
   unsupportedModules:[...new Set([...modules.filter(o=>/ParameterDynamic|AxisLock|SubUV|LocationEmitter|MeshRotation/.test(o.Type)).map(o=>o.Type),...(modules.filter(o=>o.Type==='ParticleModuleOrbit').length>1?['ChainedParticleOrbit']:[]),...(required.ScreenAlignment&&required.ScreenAlignment!=='PSA_Square'?['ScreenAlignment:'+required.ScreenAlignment]:[])])]};
 }
 return emitters;
}
export async function prepareNativeParticles(input,output){
 const stat=await fs.stat(input),documents=stat.isDirectory()?await Promise.all((await fs.readdir(input)).filter(f=>f.endsWith('.json')).sort().map(async f=>['War/Content/FX/'+f.slice(0,-5)+'.'+f.slice(0,-5),JSON.parse(await fs.readFile(path.join(input,f),'utf8'))])):Object.entries(JSON.parse(await fs.readFile(input,'utf8')));
 const systems=Object.fromEntries(documents.map(([key,exports])=>[key,compileNativeParticleModules(exports)]));
 await fs.writeFile(output,JSON.stringify({version:1,source:'Native Cascade emitter modules; generated by prepare-native-particles.mjs',systems},null,2)+'\n');
 return systems;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href){
 const [input,output]=process.argv.slice(2);if(!input||!output)throw Error('Usage: node prepare-native-particles.mjs <particle-systems.json or directory> <output.json>');
 console.log('Prepared '+Object.keys(await prepareNativeParticles(input,output)).length+' native particle systems');
}
