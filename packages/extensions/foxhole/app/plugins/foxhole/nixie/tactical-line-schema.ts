import { z } from 'zod';

export const foxholeTacticalLineStateSchema = z.object({
    x: z.number(),
    y: z.number(),
    z: z.number().optional(),
    rotation: z.number(),
    visible: z.boolean(),
    alpha: z.number(),
    scaleX: z.number(),
    scaleY: z.number(),
    locked: z.boolean().optional(),
    points: z.array(z.number()).min(4),
    scaleWithZoom: z.boolean(),
    curveMode: z.union([z.literal('polyline'), z.literal('smooth')]),
    strokeColor: z.number(),
    strokeWidth: z.number(),
    strokeAlpha: z.number(),
    strokeStyle: z.union([z.literal('solid'), z.literal('dashed')]),
    strokeDashLength: z.number(),
    strokeDashGap: z.number(),
    startCap: z.union([z.literal('none'), z.literal('arrow'), z.literal('flag'), z.literal('circle')]),
    endCap: z.union([z.literal('none'), z.literal('arrow'), z.literal('flag'), z.literal('circle')]),
    decoratorMode: z.union([
        z.literal('none'),
        z.literal('semicircle'),
        z.literal('triangle'),
        z.literal('tick'),
        z.literal('block'),
        z.literal('cross'),
        z.literal('arrow'),
    ]),
    decoratorSide: z.union([z.literal('left'), z.literal('right'), z.literal('both')]),
    decoratorSize: z.number(),
    decoratorSpacing: z.number(),
    decoratorFill: z.boolean(),
    decoratorColor: z.number(),
    decoratorAlpha: z.number(),
    presetId: z.union([
        z.literal('frontline'),
        z.literal('advance'),
        z.literal('fallback'),
        z.literal('fortified'),
        z.literal('cross'),
    ]),
});
