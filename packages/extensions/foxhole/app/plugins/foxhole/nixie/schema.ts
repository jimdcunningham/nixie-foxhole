import { z } from 'zod';

export const foxholeStructureStateSchema = z.object({
    x: z.number(),
    y: z.number(),
    z: z.number().optional(),
    rotation: z.number(),
    visible: z.boolean(),
    alpha: z.number(),
    scaleX: z.number(),
    scaleY: z.number(),
    locked: z.boolean().optional(),
    foxholeKey: z.string(),
    faction: z.union([z.literal('c'), z.literal('w'), z.null()]).optional(),
    colorHex: z.string().optional(),
    destroyed: z.boolean().optional(),
    packaged: z.boolean().optional(),
    blueprint: z.boolean().optional(),
    tint: z.number().optional(),
    brightness: z.number().optional(),
    anchorX: z.number(),
    anchorY: z.number(),
    modificationVariantIds: z.record(z.string(), z.string()).default({}),
    markedItemCodenames: z.array(z.string().min(1)).default([]),
    markedStockpileItems: z.record(z.string(), z.array(z.string().min(1))).optional(),
    productionOrders: z.array(z.object({
        recipeId: z.string().min(1),
        parent: z.boolean().default(false),
        cycles: z.number().positive().nullable().default(null),
        label: z.string().max(200).nullable().default(null),
    })).default([]),
    disableProduction: z.boolean().default(false),
    maintenanceFilters: z.record(z.string(), z.unknown()).optional(),
    baseUpgrades: z.record(z.string(), z.string()).optional(),
});
