import { z } from 'zod';

export const foxholeBinocularLineStateSchema = z.object({
    x: z.number(),
    y: z.number(),
    z: z.number().optional(),
    rotation: z.number(),
    visible: z.boolean(),
    alpha: z.number(),
    scaleX: z.number(),
    scaleY: z.number(),
    locked: z.boolean().optional(),
    points: z.array(z.number()).min(4),
    scaleWithZoom: z.boolean(),
    strokeColor: z.number(),
    strokeWidth: z.number(),
    strokeAlpha: z.number(),
    multiSegmentAlpha: z.number(),
    showDistance: z.boolean(),
    showAzimuth: z.boolean(),
    showAzimuthArrows: z.boolean(),
    labelColor: z.number(),
    labelFontSize: z.number(),
    labelBackgroundColor: z.number(),
    labelBackgroundAlpha: z.number(),
    labelPadding: z.number(),
    labelStrokeWidth: z.number(),
    endpointRadius: z.number(),
    startCap: z.union([z.literal('none'), z.literal('arrow'), z.literal('circle')]),
    endCap: z.union([z.literal('none'), z.literal('arrow'), z.literal('circle')]),
    meterPixels: z.number(),
    decimals: z.number(),
});
